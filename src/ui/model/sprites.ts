const parsed = new Map<SpriteName, Sprite>();

export function parseGrid(rows: readonly string[]): Sprite {
  return rows.map((row) =>
    Array.from(row, (ch): Pixel => {
      if (ch === '.') return null;
      const index = Number(ch);
      return index >= 0 && index <= 3 && Number.isInteger(index) ? (index as PaletteIndex) : null;
    }),
  );
}

export function spriteFor(name: SpriteName): Sprite {
  let sprite = parsed.get(name);
  if (!sprite) {
    sprite = parseGrid(GRIDS[name]);
    parsed.set(name, sprite);
  }
  return sprite;
}

/** The raw rows, for validation. */
export const spriteRows = (name: SpriteName): readonly string[] => GRIDS[name];

/**
 * Run-length merged SVG path data per palette index: one `d` string per shade, so a sprite renders
 * as at most four paths of crisp pixel rects instead of up to 256 elements.
 */
export function spritePaths(sprite: Sprite): Partial<Record<PaletteIndex, string>> {
  const out: Partial<Record<PaletteIndex, string>> = {};
  sprite.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const shade = row[x];
      if (shade === null) {
        x += 1;
        continue;
      }
      let end = x + 1;
      while (end < row.length && row[end] === shade) end += 1;
      out[shade] = `${out[shade] ?? ''}M${x} ${y}h${end - x}v1h-${end - x}z`;
      x = end;
    }
  });
  return out;
}
